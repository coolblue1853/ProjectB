        if len(fr) != len(m["times"]):  # 키 프레임 수가 바뀌어도 시간 목록을 맞춘다(모자라면 마지막 값 반복)
            m["times"] = (m["times"] + [m["times"][-1]] * len(fr))[:len(fr)]
        refs = ref_frames(m["ref"], len(fr))
