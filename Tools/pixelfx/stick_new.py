def legs(front, back):
    """관절표(Docs/MotionBodyTable.md) 다리 → 스켈레톤 각도. front/back = (보폭 px, 무릎 굽힘 °). 앞다리 = L, 뒷다리 = R(LUNGE 와 같은 배치)."""
    fs, fb = front
    bs, bb = back
    ft = -90 + fs * 5 + fb * 0.5
    bt = -90 - bs * 4 + bb * 0.3
    return (bt, bt - bb, ft, ft - fb)


